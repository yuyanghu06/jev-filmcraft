import assert from 'node:assert/strict';
import { writeFile, readFile, stat } from 'node:fs/promises';
import { join } from 'node:path';
import { setTimeout } from 'node:timers/promises';
import { resultData } from '../dist/core.js';
import { makeFixtures } from './fixtures.mjs';

/** An ordinary MCP client can run this entire edit. The test and demo share the same scenario. */
export async function editDemo(client, directory) {
  const events = [];
  const call = async (name, args = {}) => {
    const result = await client.callTool({ name: `filmcraft_${name}`, arguments: args });
    assert(!result.isError, `${name}: ${JSON.stringify(result.content)}`);
    const data = resultData(result);
    events.push({ tool: `filmcraft_${name}`, arguments: args });
    return data;
  };
  const exec = (id, params = {}) => call('execute', { id, params });
  const media = await makeFixtures(directory);
  await call('project_new', { name: 'Jev MCP editing proof' });
  const { bin } = await call('bin_create', { name: 'Generated assets' });
  const imported = await call('media_import', { paths: [media.image, media.audio], bin });
  assert.equal(imported.errors.length, 0);
  assert.equal(imported.items.length, 2);
  const [picture, sound] = imported.items;
  const { sequence } = await call('sequence_create', { name: 'MCP edit', width: 320, height: 180, fps: 24, video: 2, audio: 1 });
  const tick = 254016000000;
  await call('clip_place', { item: picture, track: 'V1', seconds: 0, duration: 2 * tick, audio: false });
  await call('clip_place', { item: sound, track: 'A1', seconds: 0, duration: 2 * tick, video: false });
  let state = await call('sequence_inspect');
  assert.equal(state.durationFrames, 48);
  const video = state.video[0].items[0].clip, audio = state.audio[0].items[0].clip;
  await call('clip_split', { clip: video, seconds: 1 });
  state = await call('sequence_inspect');
  assert.equal(state.video[0].items.length, 2);
  const second = state.video[0].items[1].clip;
  await call('clip_trim', { clip: second, edge: 'out', deltaFrames: -6 });
  assert.equal((await call('sequence_inspect')).video[0].items[1].durationFrames, 18);
  await call('undo');
  assert.equal((await call('sequence_inspect')).video[0].items[1].durationFrames, 24);
  await call('redo');
  await call('undo');
  await call('effect_apply', { clips: [video], effect: 'lumetri' });
  await call('effect_set', { clip: video, effect: 'lumetri', param: 'exposure', value: 0.25 });
  await call('effect_set', { clip: video, effect: 'motion', param: 'scale', value: 100, time: 0, keyframe: true });
  await call('effect_set', { clip: video, effect: 'motion', param: 'scale', value: 110, time: tick / 2, keyframe: true });
  await call('audio_gain', { clips: [audio], mode: 'set', db: -6 });
  await call('mixer_set', { strip: 'A1', volumeDb: -3, pan: 0.1 });
  const mix = await call('mixer_inspect');
  assert(mix.strips.some(s => s.volumeDb === -3 && s.pan === 0.1));
  await call('transition_video', { clip: video, effect: 'cross_dissolve', edge: 'in', frames: 6 });
  const title = await call('title_create', { text: 'JEV + FILMCRAFT', time: 0, seconds: 2, track: 1, size: 22, position: [160, 80] });
  await call('graphic_set', { clip: title.clip, layer: title.layer, props: { fill_color: '#ffffff', align: 'center' } });
  const caption = await call('caption_add', { text: 'Edited entirely through MCP', seconds: 0, durationSeconds: 1.8 });
  await call('caption_set_text', { caption: caption.caption, text: 'MCP → API → FilmCraft' });
  await call('marker_add', { seconds: 1, name: 'Split point', comment: 'Created through the Jev plugin' });
  state = await call('sequence_inspect');
  assert.equal(state.audio[0].items[0].gainDb, -6);
  assert.equal(state.video[0].items[0].effects.find(e => e.effect === 'motion').params.scale.keyframes, 2);
  assert.equal(state.video[0].items[0].effects.find(e => e.effect === 'lumetri').params.exposure.value, 'Float(0.25)');
  assert.equal(state.video[0].transitions.length, 1);
  assert.equal(state.markers.length, 1);
  await call('playhead_set', { seconds: 1 });
  const beforePreview = await call('sequence_inspect');
  const preview = await client.callTool({ name: 'filmcraft_render_preview', arguments: { seconds: 0.5, max_side: 320 } });
  assert(!preview.isError, JSON.stringify(preview.content));
  const image = preview.content.find(c => c.type === 'image');
  assert(image, 'MCP must return real image content');
  const previewBytes = Buffer.from(image.data, 'base64');
  assert.equal(previewBytes.subarray(1, 4).toString(), 'PNG');
  await writeFile(join(directory, 'preview.png'), previewBytes);
  assert.deepEqual((await call('sequence_inspect')).playhead, beforePreview.playhead);
  await call('captions_export', { path: join(directory, 'captions.srt') });
  assert.match(await readFile(join(directory, 'captions.srt'), 'utf8'), /MCP/);
  await call('interchange_export', { path: join(directory, 'timeline.otio'), format: 'otio' });
  const projectPath = join(directory, 'edit.fcproj');
  await call('project_save', { path: projectPath });
  await call('project_new', { name: 'Temporary empty project' });
  await call('project_open', { path: projectPath });
  state = await call('sequence_inspect');
  assert.equal(state.id, sequence);
  assert.equal(state.video[0].items.length, 2);
  assert.equal(state.video[1].items[0].clip, title.clip);
  const exported = await call('export_start', { path: join(directory, 'edit.mp4'), format: 'h264', burnCaptions: true });
  assert.equal(typeof exported.job, 'number');
  const deadline = Date.now() + 120_000;
  let job;
  do {
    const jobs = await call('jobs_list');
    job = jobs.find(j => j.id === exported.job);
    assert(job, 'Export job must be discoverable');
    if (job.finished) break;
    await setTimeout(100);
  } while (Date.now() < deadline);
  assert(job.finished, `Export did not finish: ${JSON.stringify(job)}`);
  assert(!job.result?.error, `Export failed: ${JSON.stringify(job)}`);
  assert.equal(job.offlineMedia?.length ?? 0, 0);
  assert((await stat(join(directory, 'edit.mp4'))).size > 1000);
  assert.equal((await readFile(join(directory, 'edit.mp4'))).subarray(4, 8).toString(), 'ftyp');
  // Import the rendered video back through FilmCraft's decoder; verify it is playable.
  const delivered = await call('media_import', { paths: [join(directory, 'edit.mp4')] });
  assert.equal(delivered.errors.length, 0);
  const verifySequence = await call('sequence_create', { name: 'Export verification', fromItem: delivered.items[0] });
  assert(verifySequence.sequence);
  const decoded = await client.callTool({ name: 'filmcraft_render_preview', arguments: { seconds: 0.5, max_side: 160 } });
  assert(!decoded.isError && decoded.content.some(c => c.type === 'image'), 'Export must decode back into a real frame');
  await call('sequence_open', { item: sequence });
  await call('project_save');
  const summary = { toolsCalled: events.length + 2, sequence, exportJob: job, output: directory, files: ['edit.fcproj', 'edit.mp4', 'preview.png', 'captions.srt', 'timeline.otio'], events };
  await writeFile(join(directory, 'report.json'), JSON.stringify(summary, null, 2));
  return summary;
}
